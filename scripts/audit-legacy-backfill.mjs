import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const sourceFiles = [
  "deploy-worker/src/index.js",
  "migrations/001_employee_anchor_schema.sql",
  "migration-drafts/002_commercial_bootstrap.sql",
  "MIGRATION_SCHEMA_CONTRACT.md"
];

function read(relativePath) {
  const filePath = path.join(root, relativePath);
  return fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : "";
}

const corpus = sourceFiles.map(read).join("\n");

const mappings = [
  {
    legacy: "corpid",
    target: "company_id, property_id",
    risk: "P0",
    action:
      "Seed a default company/property for legacy rows, then require every future query to use scoped identifiers."
  },
  {
    legacy: "sessions",
    target: "handover_sessions",
    risk: "P0",
    action:
      "Convert session totals to *_fils after backend recomputation; do not trust cash_handover/gross_received from the browser."
  },
  {
    legacy: "transactions",
    target: "transactions, payments, receivables",
    risk: "P0",
    action:
      "Convert REAL amount/due/paid/deficit fields to integer fils; split payment application from receivable generation."
  },
  {
    legacy: "arrears",
    target: "receivables, arrear_tasks",
    risk: "P1",
    action:
      "Treat legacy arrears as open receivables plus staff follow-up tasks; reconcile cleared rows separately."
  },
  {
    legacy: "arrear_tasks",
    target: "arrear_tasks linked to receivables",
    risk: "P1",
    action:
      "Preserve promise_date, promise_amount, status, notes, assigned staff, and closure fields; do not make task amount the accounting source."
  },
  {
    legacy: "deposit_ledger",
    target: "deposit_ledger",
    risk: "P0",
    action:
      "Convert amount/delta/balance_after REAL values to *_fils and verify every tenant_card_id balance can be reconstructed."
  },
  {
    legacy: "entry_events, audit_logs",
    target: "audit_events",
    risk: "P1",
    action:
      "Preserve actor, role, entity, before/after values, reason, and timestamp; flag rows with missing actor as reconciliation exceptions."
  },
  {
    legacy: "employee_users, active_sessions",
    target: "users, property_memberships, session/auth tables",
    risk: "P1",
    action:
      "Migrate only account identity and role scope; do not migrate local dev passwords or sessions as production credentials."
  },
  {
    legacy: "app_settings",
    target: "settings tables or versioned config tables",
    risk: "P2",
    action:
      "Split rent configuration into bed_rent_config_versions and keep other settings scoped by company/property."
  }
];

const requiredLegacySignals = [
  "CREATE TABLE IF NOT EXISTS sessions",
  "transactions",
  "arrear_tasks",
  "entry_events",
  "deposit_ledger",
  "audit_logs",
  "DELETE FROM transactions",
  "REAL"
];

const requiredTargetSignals = [
  "handover_sessions",
  "receivables",
  "payments",
  "amount_fils",
  "company_id",
  "property_id",
  "audit_events"
];

const findings = [];

for (const signal of requiredLegacySignals) {
  if (!corpus.includes(signal)) {
    findings.push({ severity: "P2", issue: `Legacy signal not found in static corpus: ${signal}` });
  }
}

for (const signal of requiredTargetSignals) {
  if (!corpus.includes(signal)) {
    findings.push({ severity: "P1", issue: `Target signal not found in static corpus: ${signal}` });
  }
}

const lines = [
  "# Legacy Backfill Audit",
  "",
  "Generated by `scripts/audit-legacy-backfill.mjs`.",
  "",
  "Mode: read-only static audit.",
  "",
  "No D1 connection was opened. No SQL was executed. No backfill was performed.",
  "",
  "## Source Files Scanned",
  "",
  ...sourceFiles.map((file) => `- \`${file}\``),
  "",
  "## Legacy-To-Commercial Mapping",
  "",
  "| Legacy source | Commercial target | Risk | Required action |",
  "| --- | --- | --- | --- |",
  ...mappings.map(
    (row) => `| \`${row.legacy}\` | \`${row.target}\` | ${row.risk} | ${row.action} |`
  ),
  "",
  "## Mandatory Reconciliation Rules",
  "",
  "- Every legacy money value must be converted to integer AED fils before insertion into commercial tables.",
  "- Legacy `REAL` values must be rounded explicitly and differences must be reported by row.",
  "- Legacy browser/session totals are comparison inputs only; backend recomputed totals are the accounting target.",
  "- Hard-deleted legacy semantics must become void/audit semantics in the commercial model.",
  "- Backfill must be idempotent and produce inserted/skipped/conflicted/failed counts.",
  "- Rows without tenant/property scope must be assigned through a reviewed default mapping, never by guessing inside request handlers.",
  "- Deposit balances must reconcile per `tenant_card_id` after conversion.",
  "- Receivables must reconcile by bed, tenant card, period start, period end, due, paid, and remaining amount.",
  "",
  "## Static Findings",
  "",
  "| Severity | Issue |",
  "| --- | --- |"
];

if (findings.length) {
  for (const finding of findings) {
    lines.push(`| ${finding.severity} | ${finding.issue} |`);
  }
} else {
  lines.push("| P3 | Static mapping signals present. This is not a data reconciliation pass. |");
}

lines.push(
  "",
  "## Backfill No-Go Conditions",
  "",
  "- Do not run backfill against production before a remote D1 backup exists.",
  "- Do not run backfill before a staging rehearsal compares old and new totals.",
  "- Do not run backfill if any source table has unknown columns that affect money, tenant, property, period, deposit, or audit state.",
  "- Do not run backfill if employee entry/export smoke tests fail on a clean local D1 after migration.",
  "- Do not run backfill if rollback/restore steps are not written."
);

fs.writeFileSync(path.join(root, "LEGACY_BACKFILL_AUDIT.md"), `${lines.join("\n")}\n`);
console.log(`Legacy backfill audit written: ${findings.length} static findings`);
