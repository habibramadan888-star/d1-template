#!/usr/bin/env node

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const docsDir = path.join(rootDir, "docs");
const reportPath = path.join(docsDir, "PHASE_3P5_HARDENING_EVIDENCE_REPORT.md");
const resultPath = path.join(docsDir, "PHASE_3P5_HARDENING_EVIDENCE_RESULTS.json");

const generatedFilesRestoredAfterEvidenceRead = [
  path.join(rootDir, "COMMERCIAL_LAUNCH_READINESS_MATRIX.md"),
  path.join(rootDir, "COMMERCIAL_LAUNCH_READINESS_RESULT.md")
];

const commandsToRun = [
  {
    id: "typecheck",
    label: "Syntax and module scan",
    command: process.execPath,
    args: ["scripts/check-syntax.mjs"],
    required: true
  },
  {
    id: "security-secrets",
    label: "Secret hygiene",
    command: process.execPath,
    args: ["scripts/check-secrets.mjs"],
    required: true
  },
  {
    id: "full-test-suite",
    label: "Full local test suite",
    command: process.execPath,
    args: ["--test", "--test-concurrency=1", "tests/**/*.spec.mjs"],
    required: true
  },
  {
    id: "commercial-launch-gate",
    label: "Commercial launch gate",
    command: process.execPath,
    args: ["scripts/gate-commercial-launch-readiness.mjs"],
    required: true,
    mustContain: "COMMERCIAL_LAUNCH_READINESS=PRODUCTION_NO_GO"
  }
];

const phaseEvidenceFiles = [
  {
    id: "phase-0",
    label: "Phase 0 readonly smoke",
    file: "docs/PHASE_0_TEST_RESULTS_FINAL.json",
    passField: "passed",
    totalField: "totalTests",
    allowedDecisions: ["GO"]
  },
  {
    id: "phase-1",
    label: "Phase 1 write operation validation",
    file: "docs/PHASE_1_COMPLETE_RESULTS.json",
    passField: "pass",
    totalField: "tests",
    allowedDecisions: ["GO"]
  },
  {
    id: "phase-2a",
    label: "Phase 2A feature flag validation",
    file: "docs/PHASE_2A_FEATURE_FLAG_RESULTS.json",
    passField: "pass",
    totalField: "tests",
    allowedDecisions: ["GO"]
  },
  {
    id: "phase-3",
    label: "Phase 3 safe execution rehearsal",
    file: "docs/PHASE_3_EXECUTION_SIMULATION_RESULTS.json",
    passField: null,
    totalField: null,
    allowedDecisions: ["SIMULATION_COMPLETE_NOT_PRODUCTION_APPROVED"]
  }
];

const unexecutedClaims = [
  "No 8-12 hour sustained load window was executed by this script.",
  "No 100-user live concurrency or external load test was executed by this script.",
  "No real production-copy deployment or 24-hour stability window was executed by this script.",
  "No penetration test was executed by this script beyond repository secret hygiene and existing automated tests.",
  "No production approval, production-ready score, or human sign-off was generated by this script."
];

function snapshotFiles(files) {
  const snapshot = new Map();
  for (const file of files) {
    snapshot.set(file, existsSync(file) ? readFileSync(file, "utf8") : null);
  }
  return snapshot;
}

function restoreFiles(snapshot) {
  for (const [file, content] of snapshot.entries()) {
    if (content === null) {
      if (existsSync(file)) {
        rmSync(file);
      }
      continue;
    }

    writeFileSync(file, content);
  }
}

function readJson(relativeFile) {
  const absoluteFile = path.join(rootDir, relativeFile);
  if (!existsSync(absoluteFile)) {
    return { ok: false, reason: "missing" };
  }

  try {
    return { ok: true, data: JSON.parse(readFileSync(absoluteFile, "utf8")) };
  } catch (error) {
    return { ok: false, reason: error.message };
  }
}

function runCommand({ command, args, mustContain }) {
  const startedAt = new Date().toISOString();
  const startedMs = Date.now();
  const result = spawnSync(command, args, {
    cwd: rootDir,
    encoding: "utf8",
    maxBuffer: 128 * 1024 * 1024
  });
  const output = `${result.stdout || ""}${result.stderr || ""}`;
  const containsRequiredText = mustContain ? output.includes(mustContain) : true;
  const passed = result.status === 0 && containsRequiredText;

  return {
    invocation: `${command} ${args.join(" ")}`,
    startedAt,
    finishedAt: new Date().toISOString(),
    elapsedMs: Date.now() - startedMs,
    exitCode: result.status,
    error: result.error ? result.error.message : null,
    containsRequiredText,
    passed,
    outputTail: passed ? "" : output.slice(-12000),
    parsed: parseCommandOutput(output)
  };
}

function parseCommandOutput(output) {
  const parsed = {};
  const syntaxMatch = output.match(/Syntax check passed for\s+(\d+)\s+file/);
  if (syntaxMatch) {
    parsed.syntaxFiles = Number(syntaxMatch[1]);
  }

  if (output.includes("Secret hygiene check passed")) {
    parsed.secretHygiene = "passed";
  }

  const testsMatch = output.match(/(?:^|\n).*tests\s+(\d+)/);
  const passMatch = output.match(/(?:^|\n).*pass\s+(\d+)/);
  const failMatch = output.match(/(?:^|\n).*fail\s+(\d+)/);
  if (testsMatch && passMatch && failMatch) {
    parsed.tests = Number(testsMatch[1]);
    parsed.pass = Number(passMatch[1]);
    parsed.fail = Number(failMatch[1]);
  }

  const gateMatch = output.match(/COMMERCIAL_LAUNCH_READINESS=([A-Z_]+)/);
  if (gateMatch) {
    parsed.commercialLaunchReadiness = gateMatch[1];
  }

  const noGoMatch = output.match(/COMMERCIAL_LAUNCH_NO_GO=(\d+)/);
  if (noGoMatch) {
    parsed.commercialLaunchNoGoAreas = Number(noGoMatch[1]);
  }

  const manualMatch = output.match(/COMMERCIAL_LAUNCH_MANUAL_REQUIRED=(\d+)/);
  if (manualMatch) {
    parsed.commercialLaunchManualRequiredAreas = Number(manualMatch[1]);
  }

  return parsed;
}

function collectPhaseEvidence() {
  return phaseEvidenceFiles.map((item) => {
    const loaded = readJson(item.file);
    if (!loaded.ok) {
      return {
        ...item,
        passed: false,
        pass: 0,
        total: 0,
        decision: "MISSING",
        reason: loaded.reason
      };
    }

    if (item.id === "phase-3") {
      const finalDecision = loaded.data.finalDecision || "UNKNOWN";
      const readinessEvidence = loaded.data.phaseEvidence?.find(
        (phase) => phase.id === "phase-3-readiness"
      );
      const passed =
        loaded.data.checksPassed === true &&
        loaded.data.productionApproved === false &&
        loaded.data.humanSignoffsRecorded === false &&
        item.allowedDecisions.includes(finalDecision);

      return {
        ...item,
        passed,
        pass: Number(readinessEvidence?.pass || 0),
        total: Number(readinessEvidence?.total || 0),
        decision: finalDecision,
        productionApproved: loaded.data.productionApproved,
        humanSignoffsRecorded: loaded.data.humanSignoffsRecorded
      };
    }

    const pass = Number(loaded.data[item.passField] || 0);
    const total = Number(loaded.data[item.totalField] || 0);
    const decision = loaded.data.decision || "UNKNOWN";
    return {
      ...item,
      passed: total > 0 && pass === total && item.allowedDecisions.includes(String(decision)),
      pass,
      total,
      decision
    };
  });
}

function buildMarkdownReport(payload) {
  const commandRows = payload.commands
    .map(
      (item) =>
        `| ${item.label} | ${item.result.passed ? "PASS" : "FAIL"} | ${Math.round(
          item.result.elapsedMs / 1000
        )}s | \`${item.result.invocation}\` |`
    )
    .join("\n");

  const phaseRows = payload.phaseEvidence
    .map(
      (item) =>
        `| ${item.label} | ${item.passed ? "PASS" : "FAIL"} | ${item.pass}/${item.total} | ${item.decision} | \`${item.file}\` |`
    )
    .join("\n");

  const commandMetricRows = payload.commands
    .map((item) => {
      const metrics = Object.entries(item.result.parsed)
        .map(([key, value]) => `${key}=${value}`)
        .join(", ");
      return `| ${item.label} | ${metrics || "n/a"} |`;
    })
    .join("\n");

  const unexecutedRows = payload.unexecutedClaims.map((claim) => `- ${claim}`).join("\n");

  return `# Phase 3.5 Hardening Evidence Report

Generated: ${payload.finishedAt}

Decision: \`${payload.finalDecision}\`

Production status: \`PRODUCTION_NO_GO\`.

## Scope

This report replaces the pasted auto-approval script with a verifiable local evidence run. It executes repository checks, records existing phase evidence, and explicitly refuses unsupported production-readiness claims.

## Commands Executed

| Check | Status | Duration | Invocation |
| --- | --- | ---: | --- |
${commandRows}

## Parsed Command Metrics

| Check | Metrics |
| --- | --- |
${commandMetricRows}

## Existing Phase Evidence

| Evidence | Status | Count | Decision | File |
| --- | --- | ---: | --- | --- |
${phaseRows}

## Unsupported Claims Not Made

${unexecutedRows}

## Safety Boundaries

- No production deployment was performed.
- No production-copy deployment was performed.
- No remote D1 write or migration was performed.
- No production feature flag was enabled.
- No 8-12 hour stability result was fabricated.
- No 99/100 quality score was fabricated.
- No human sign-off was fabricated.
- The commercial launch gate still reports \`PRODUCTION_NO_GO\`.

## Final Result

\`${payload.finalDecision}\`

Next valid step: run the real Phase 3 production-copy dry-run with live monitoring, real team coverage, rollback timing, external load/security evidence if required, and manual sign-offs.
`;
}

async function main() {
  const startedAt = new Date().toISOString();

  console.log("PHASE 3.5 HARDENING EVIDENCE RUN");
  console.log(`Started: ${startedAt}`);
  console.log("Production status must remain PRODUCTION_NO_GO.");

  mkdirSync(docsDir, { recursive: true });
  const generatedFileSnapshot = snapshotFiles(generatedFilesRestoredAfterEvidenceRead);

  const commands = [];
  for (const commandConfig of commandsToRun) {
    console.log(`Running: ${commandConfig.label}`);
    const result = runCommand(commandConfig);
    commands.push({
      id: commandConfig.id,
      label: commandConfig.label,
      required: commandConfig.required,
      result
    });

    if (!result.passed) {
      console.error(result.outputTail);
    }
  }

  const phaseEvidence = collectPhaseEvidence();
  const commandsPassed = commands.every((item) => !item.required || item.result.passed);
  const evidencePassed = phaseEvidence.every((item) => item.passed);
  const commercialGate = commands.find((item) => item.id === "commercial-launch-gate")?.result;
  const productionNoGoMaintained =
    commercialGate?.parsed?.commercialLaunchReadiness === "PRODUCTION_NO_GO";
  const checksPassed = commandsPassed && evidencePassed && productionNoGoMaintained;

  const payload = {
    startedAt,
    finishedAt: new Date().toISOString(),
    environment: process.env.ENVIRONMENT || "local",
    mode: "PHASE3P5_EVIDENCE_ONLY",
    commands,
    phaseEvidence,
    unexecutedClaims,
    commandsPassed,
    evidencePassed,
    productionNoGoMaintained,
    checksPassed,
    productionApproved: false,
    qualityScoreClaimed: false,
    humanSignoffsRecorded: false,
    finalDecision: checksPassed
      ? "PHASE3P5_EVIDENCE_COMPLETE_NOT_PRODUCTION_APPROVED"
      : "PHASE3P5_EVIDENCE_BLOCKED"
  };

  restoreFiles(generatedFileSnapshot);

  writeFileSync(resultPath, `${JSON.stringify(payload, null, 2)}\n`);
  writeFileSync(reportPath, buildMarkdownReport(payload));

  console.log(`Decision: ${payload.finalDecision}`);
  console.log(`Report: ${path.relative(rootDir, reportPath)}`);
  console.log("Production approval: false");

  if (!checksPassed) {
    process.exit(1);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
