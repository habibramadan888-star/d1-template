import fs from "node:fs";
import path from "node:path";
import prettier from "prettier";

const root = process.cwd();
const outputPath = path.join(root, "RUNTIME_DDL_STATIC_SCAN.md");

const files = [
  path.join(root, "deploy-worker", "src", "index.js"),
  path.join(root, "deploy-worker", "src", "index.embedded.js")
].filter((file) => fs.existsSync(file));

const localMigrationPath = path.join(root, "migrations", "local", "001_clean_legacy_bootstrap.sql");
const localMigration = fs.existsSync(localMigrationPath)
  ? fs.readFileSync(localMigrationPath, "utf8")
  : "";

function rel(file) {
  return path.relative(root, file).replaceAll("\\", "/");
}

function lineNumberFor(text, index) {
  return text.slice(0, index).split(/\r?\n/).length;
}

function coveredByLocalMigration(statement) {
  const tableMatch = statement.match(
    /\b(?:CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?|CREATE\s+INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?[A-Za-z0-9_]+\s+ON\s+|ALTER\s+TABLE\s+)([A-Za-z0-9_]+)/i
  );
  if (!tableMatch) return "unknown";
  const table = tableMatch[1];
  return new RegExp(`\\b${table}\\b`, "i").test(localMigration) ? "yes" : "no";
}

function riskFor(statement) {
  if (/ALTER\s+TABLE/i.test(statement)) return "P1 runtime schema drift";
  if (/CREATE\s+TABLE/i.test(statement)) return "P1 runtime bootstrap side effect";
  if (/CREATE\s+INDEX/i.test(statement)) return "P2 runtime index side effect";
  return "P3 review";
}

const findings = [];

for (const file of files) {
  const text = fs.readFileSync(file, "utf8");
  const patterns = [
    /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[A-Za-z0-9_]+/gi,
    /CREATE\s+INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?[A-Za-z0-9_]+\s+ON\s+[A-Za-z0-9_]+/gi,
    /ALTER\s+TABLE\s+[A-Za-z0-9_]+/gi,
    /empAddColumn\s*\(\s*env\s*,\s*"[^"]+"\s*,\s*"[^"]+"\s*,\s*"[^"]+"/g
  ];

  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) {
      const statement = match[0].replace(/\s+/g, " ").trim();
      findings.push({
        file: rel(file),
        line: lineNumberFor(text, match.index ?? 0),
        statement,
        covered: coveredByLocalMigration(statement),
        risk: riskFor(statement)
      });
    }
  }
}

function buildReport() {
  const rows = findings.map(
    (item) =>
      `| \`${item.file}:${item.line}\` | \`${item.statement.replaceAll("|", "\\|")}\` | ${item.covered} | ${item.risk} | Keep until P1-002 migration cutover; do not remove automatically. |`
  );

  return [
    "# Runtime DDL Static Scan",
    "",
    "Generated by `scripts/audit-runtime-ddl.mjs`.",
    "Mode: read-only static scan.",
    "Production deploy executed: no.",
    "Production database mutation executed: no.",
    "",
    "## Summary",
    "",
    `- Files scanned: ${files.map(rel).join(", ") || "none"}`,
    `- Runtime DDL findings: ${findings.length}`,
    "- This scan includes source and embedded Worker files so source/embedded drift is visible.",
    "- Findings are not automatically fixed because runtime DDL removal requires production migration discipline.",
    "",
    "## Findings",
    "",
    "| Location | DDL Evidence | Covered By Local Migration | Risk | Recommendation |",
    "| --- | --- | --- | --- | --- |",
    ...(rows.length ? rows : ["| n/a | n/a | n/a | none | No runtime DDL detected. |"]),
    "",
    "## Commercial Meaning",
    "",
    "- P1 runtime DDL remains open while Worker request paths can create or alter schema.",
    "- Local clean bootstrap now reduces dependence on runtime DDL, but production compatibility logic still exists.",
    "- Removal should happen only after reviewed migrations, staging rehearsal, rollback plan, and drift checks.",
    ""
  ].join("\n");
}

const report = await prettier.format(buildReport(), { parser: "markdown" });
fs.writeFileSync(outputPath, report);
console.log(`Runtime DDL static scan written: ${findings.length} findings`);
