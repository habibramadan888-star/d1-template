import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import prettier from "prettier";

const root = process.cwd();
const workerRoot = path.join(root, "deploy-worker");
const publicDir = path.join(workerRoot, "public");
const sourcePath = path.join(workerRoot, "src", "index.js");
const currentEmbeddedPath = path.join(workerRoot, "src", "index.embedded.js");
const tmpDir = path.join(root, ".tmp", "embedded-worker-dry-run");
const generatedPath = path.join(tmpDir, "index.embedded.generated.js");
const reportPath = path.join(root, "EMBEDDED_WORKER_GENERATION_DRY_RUN_RESULT.md");

function sha256(text) {
  return crypto.createHash("sha256").update(text).digest("hex");
}

function contentType(name) {
  if (name.endsWith(".html")) return "text/html; charset=utf-8";
  if (name.endsWith(".js")) return "application/javascript; charset=utf-8";
  if (name.endsWith(".css")) return "text/css; charset=utf-8";
  if (name.endsWith(".json")) return "application/json; charset=utf-8";
  if (name.endsWith(".png")) return "image/png";
  if (name.endsWith(".jpg") || name.endsWith(".jpeg")) return "image/jpeg";
  if (name.endsWith(".svg")) return "image/svg+xml; charset=utf-8";
  return "application/octet-stream";
}

function embeddedAssets() {
  const assets = {};
  if (!fs.existsSync(publicDir)) return assets;
  for (const name of fs.readdirSync(publicDir)) {
    const full = path.join(publicDir, name);
    if (!fs.statSync(full).isFile()) continue;
    assets[`/${name}`] = {
      type: contentType(name),
      b64: fs.readFileSync(full).toString("base64")
    };
  }
  return assets;
}

function generateEmbedded() {
  const assets = embeddedAssets();
  const embeddedHelper = `
// Generated by scripts/generate-embedded-worker-dry-run.mjs for dry-run review only.
// Source: deploy-worker/src/index.js
// Source SHA-256: ${sha256(fs.readFileSync(sourcePath, "utf8"))}
const EMBEDDED_ASSETS = ${JSON.stringify(assets)};
function embeddedAssetResponse(pathname) {
  const clean = pathname === "/" ? "/index.html" : (pathname.endsWith(".html") || pathname.endsWith(".js") ? pathname : pathname + ".html");
  const asset = EMBEDDED_ASSETS[clean] || EMBEDDED_ASSETS[pathname];
  if (!asset) return null;
  const binary = atob(asset.b64);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return new Response(bytes, { headers: { "Content-Type": asset.type, "Cache-Control": "no-store" } });
}
`;

  const original = fs.readFileSync(sourcePath, "utf8");
  const marker = `  if (env.ASSETS) {
    return env.ASSETS.fetch(request);
  }
  return new Response("Homelink Finance API is running. Use /auth/login for authentication.", {`;
  const replacement = `  if (env.ASSETS) {
    return env.ASSETS.fetch(request);
  }
  const embeddedResponse = embeddedAssetResponse(path);
  if (embeddedResponse) return embeddedResponse;
  return new Response("Homelink Finance API is running. Use /auth/login for authentication.", {`;
  const generated = embeddedHelper + original.replace(marker, replacement);
  if (!generated.includes("const embeddedResponse = embeddedAssetResponse(path);")) {
    throw new Error("embedded fallback injection failed");
  }
  return { generated, assetCount: Object.keys(assets).length };
}

function checkCritical(text) {
  const items = [
    "/api/staging/handover/commit",
    "ENABLE_HANDOVER_ATOMIC_STAGING",
    "HSC_ALLOWED_APP_ENVS",
    "handover_commits",
    "handover_commit_rows",
    "handover_idempotency_keys",
    "/api/delete_session",
    "voided_at",
    "void_reason",
    "void_source"
  ];
  return items.map((item) => ({ item, present: text.includes(item) }));
}

const { generated, assetCount } = generateEmbedded();
fs.mkdirSync(tmpDir, { recursive: true });
fs.writeFileSync(generatedPath, generated, "utf8");

const currentEmbedded = fs.existsSync(currentEmbeddedPath)
  ? fs.readFileSync(currentEmbeddedPath, "utf8")
  : "";
const currentHash = sha256(currentEmbedded);
const generatedHash = sha256(generated);
const currentCritical = checkCritical(currentEmbedded);
const generatedCritical = checkCritical(generated);
const currentMissing = currentCritical.filter((item) => !item.present);
const generatedMissing = generatedCritical.filter((item) => !item.present);
const status = generatedMissing.length
  ? "FAIL"
  : currentHash === generatedHash
    ? "PASS"
    : "WARNING";

const markdown = await prettier.format(
  [
    "# Embedded Worker Dry-Run Generation Result",
    "",
    "Scope: P1-006 dry-run generation. This script writes only to `.tmp/embedded-worker-dry-run/` and does not overwrite `deploy-worker/src/index.embedded.js`.",
    "",
    "## Summary",
    "",
    `- Result: **${status}**`,
    `- Generated artifact: \`${path.relative(root, generatedPath)}\``,
    `- Embedded assets included: ${assetCount}`,
    `- Current embedded size: ${currentEmbedded.length} bytes`,
    `- Dry-run generated size: ${generated.length} bytes`,
    `- Current embedded SHA-256: \`${currentHash}\``,
    `- Dry-run generated SHA-256: \`${generatedHash}\``,
    `- Hashes match: ${currentHash === generatedHash ? "Yes" : "No"}`,
    "",
    "## Critical Item Presence",
    "",
    "| Item | Current Embedded | Dry-Run Generated |",
    "| --- | --- | --- |",
    ...generatedCritical.map((row) => {
      const current = currentCritical.find((item) => item.item === row.item);
      return `| \`${row.item}\` | ${current?.present ? "Yes" : "No"} | ${row.present ? "Yes" : "No"} |`;
    }),
    "",
    "## Interpretation",
    "",
    currentMissing.length
      ? `- Current embedded artifact is missing ${currentMissing.length} critical item(s): ${currentMissing.map((item) => `\`${item.item}\``).join(", ")}.`
      : "- Current embedded artifact contains the checked critical items.",
    generatedMissing.length
      ? `- Dry-run generation is missing ${generatedMissing.length} critical item(s); generator needs review.`
      : "- Dry-run generated artifact contains all checked critical items.",
    currentHash === generatedHash
      ? "- Current embedded artifact matches dry-run output for this generator."
      : "- Current embedded artifact differs from dry-run output; controlled write requires human diff review.",
    "",
    "## Gate",
    "",
    "- This dry-run is not a deployment.",
    "- This dry-run is not approval to overwrite `index.embedded.js`.",
    "- Controlled write requires explicit human approval, route diff review, secret scan, and full validation.",
    ""
  ].join("\n"),
  { parser: "markdown" }
);

fs.writeFileSync(reportPath, markdown);

console.log(`EMBEDDED_WORKER_DRY_RUN_RESULT=${status}`);
console.log(`EMBEDDED_WORKER_DRY_RUN_PATH=${path.relative(root, generatedPath)}`);
console.log(`EMBEDDED_WORKER_CURRENT_MISSING=${currentMissing.length}`);
console.log(`EMBEDDED_WORKER_GENERATED_MISSING=${generatedMissing.length}`);
